CREATE DATABASE IF NOT EXISTS xanaan_gifts
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE xanaan_gifts;

CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS surprises (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code CHAR(6) NOT NULL UNIQUE,
  recipient_name VARCHAR(120) NOT NULL,
  welcome_text VARCHAR(255) NOT NULL,
  message_title VARCHAR(180) NOT NULL,
  message MEDIUMTEXT NOT NULL,
  theme VARCHAR(32) NOT NULL DEFAULT 'rose',
  font_style VARCHAR(32) NOT NULL DEFAULT 'elegant',
  song_title VARCHAR(180) NOT NULL DEFAULT '',
  audio_path VARCHAR(255) DEFAULT NULL,
  cover_path VARCHAR(255) DEFAULT NULL,
  bg_style VARCHAR(32) NOT NULL DEFAULT 'glow',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS photos (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  surprise_id INT UNSIGNED NOT NULL,
  file_path VARCHAR(255) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_photos_surprise FOREIGN KEY (surprise_id) REFERENCES surprises(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
